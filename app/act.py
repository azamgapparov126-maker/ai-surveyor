for _m in _MODULES:
    for _k, _v in vars(_m).items():
        if not _k.startswith("__"):
            globals()[_k] = _v
del _m, _k, _v


class _Facade(types.ModuleType):
    """
    Присваивание app.act.<имя> (тесты подменяют DIR, cleanup) доходит до модулей пакета, где это имя
    используется: раньше всё жило в одном модуле, и подмена действовала на весь акт.
    """

    def __setattr__(self, name, value):
        old = self.__dict__.get(name, _MISSING)
        for m in _MODULES:
            if name in m.__dict__ and (old is _MISSING or m.__dict__[name] is old):
                setattr(m, name, value)
        super().__setattr__(name, value)


_MISSING = object()
sys.modules[__name__].__class__ = _Facade
