def docx(lines: list) -> bytes:
    d = Docx()
    d.para(lines[0], bold=True, color="1D2C8F")
    d.para(lines[1], size=18, color="555555")
    d.title(lines[2])
    for ln in lines[3:]:
        d.para(ln)
    return d.to_bytes()


def pdf_text(lines: list) -> bytes:
    """PDF с текстовым слоем, шрифт Arial (кириллица)."""
    doc = pymupdf.open()
    page = doc.new_page(width=595, height=842)
    page.insert_font(fontname="ar", fontfile=str(FONT))
    y = 50
    for i, ln in enumerate(lines):
        size = 12 if i == 2 else 10
        rect = pymupdf.Rect(50, y, 545, y + 200)
        left = page.insert_textbox(rect, ln, fontname="ar", fontsize=size)
        used = 200 - left if left >= 0 else 40
        y += used + 6
    doc.subset_fonts()                   # в файл — только нужные буквы шрифта
    data = doc.tobytes(garbage=3, deflate=True)
    doc.close()
    return data


def pdf_scan(lines: list) -> bytes:
    """Скан: страница PDF с текстом → картинка 150 dpi → новый PDF только из картинки (текстового слоя нет)."""
    src = pymupdf.open(stream=pdf_text(lines), filetype="pdf")
    pix = src[0].get_pixmap(dpi=150, colorspace=pymupdf.csGRAY)
    png = pix.tobytes("png")
    src.close()
    doc = pymupdf.open()
    page = doc.new_page(width=595, height=842)
    page.insert_image(page.rect, stream=png)
    data = doc.tobytes(garbage=3, deflate=True)
    doc.close()
    return data


def build() -> dict:
    OUT.mkdir(parents=True, exist_ok=True)
    files = {"contract_fire.docx": docx(FIRE), "contract_pledge.pdf": pdf_text(PLEDGE),
             "contract_scan.pdf": pdf_scan(SCAN), "contract_blank.docx": docx(BLANK),
             "contract_scan.model.json": json.dumps(SCAN_MODEL, ensure_ascii=False, indent=1).encode("utf-8")}
    for name, data in files.items():
        (OUT / name).write_bytes(data)
    return {k: len(v) for k, v in files.items()}


