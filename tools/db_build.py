def pct(text):
    """Достаёт первое число в процентах из текста тарифной политики."""
    if not text:
        return None
    m = re.search(r"(\d+[.,]?\d*)\s*%", text.replace(" ", " "))
    return float(m.group(1).replace(",", ".")) if m else None


def min_rate_rows(text):
    """[(payer_type, pct)] из текста тарифа. Тип клиента: 'физ' | 'юр' | None."""
    out = []
    for m in re.finditer(r"(физ|юр)[^\d]*(\d+[.,]?\d*)\s*%", text or ""):
        out.append((m.group(1), float(m.group(2).replace(",", "."))))
    if out:
        return out
    r = pct(text)
    return [(None, r)] if r is not None else []


def pricing_mode(rate_text, gen):
    t = (rate_text or "").lower()
    if gen or "генеральн" in t:
        return "генеральный договор"
    if "программ" in t:
        return "программа"
    if "согласован" in t:
        return "по согласованию"
    if "пкм" in t:
        return "нормативный акт"
    return "ставка"


def _osgor_num(text):
    """Число из CSV прил. № 9: дробная часть через запятую, возможны пробелы. None — если не число."""
    try:
        return float(str(text).replace(" ", "").replace(" ", "").replace(",", "."))
    except (TypeError, ValueError):
        return None


def load_osgor_activities(cur):
    """
    Классификация видов деятельности ОСГОР (прил. № 9 к Правилам ПКМ № 177, разд. I, п. 3)
    из CSV библиотеки. Таблица пересобирается целиком, поэтому повторный запуск безопасен.
    Данные недоверенные: битые строки не вставляем, а показываем.
    """
    if not OSGOR_CSV.exists():
        print("  ОСГОР: файл классификации не найден:", OSGOR_CSV.name)
        return 0
    rows, bad = [], []
    with open(OSGOR_CSV, encoding="utf-8-sig", newline="") as f:
        for i, r in enumerate(csv.DictReader(f, delimiter=";"), start=2):
            no, cat, kst = _osgor_num(r.get("№")), _osgor_num(r.get("категория_проф_риска")), _osgor_num(r.get("КСТ"))
            name = (r.get("вид_деятельности") or "").strip()
            if no is None or cat is None or kst is None or not name:
                bad.append(i)
                continue
            rows.append((int(no), int(cat), kst, (r.get("код_ОКЭД_IFUT") or "").strip() or None, name))
    cur.execute("DELETE FROM osgor_activities")
    cur.executemany("INSERT INTO osgor_activities (no,category,kst,okved,name) VALUES (?,?,?,?,?)", rows)
    if bad:
        print("  ОСГОР: пропущены строки CSV (не разобраны):", ", ".join(map(str, bad[:10])))
    # контроль по заметке актуария: 934 строки, 20 категорий, КСТ 0,571…7,714
    cats = len({r[1] for r in rows})
    kmin = min((r[2] for r in rows), default=0)
    kmax = max((r[2] for r in rows), default=0)
    if len(rows) != 934 or cats != 20 or round(kmin, 3) != 0.571 or round(kmax, 3) != 7.714:
        print(f"  ОСГОР: проверьте классификацию — строк {len(rows)}, категорий {cats}, "
              f"КСТ {kmin}…{kmax} (ожидается 934 / 20 / 0.571…7.714)")
    return len(rows)


